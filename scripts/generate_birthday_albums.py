    # Also flat singles list for library "songs" tab (same songs, with album tag)
    flat_songs = []
    for alb in all_albums:
        for s in alb["songs"]:
            entry = dict(s)
            entry.setdefault("tags", [])
            entry["tags"] = list(dict.fromkeys([*(entry["tags"] or []), "birthday-collection", alb["id"]]))
            entry["customIdeas"] = (s.get("customIdeas") or "") + f" · From album: {alb['name']}"
            flat_songs.append(entry)
    library_with_songs = {
        "albums": all_albums,
        "songs": flat_songs,
        "meta": library["meta"],
    }
    lib_full = ALBUMS_DIR / "birthday-albums-library-import-full.json"
    lib_full.write_text(json.dumps(library_with_songs, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {lib_full.name} ({len(flat_songs)} singles + {len(all_albums)} albums)")

    # TypeScript seed for in-app load button
    ts_path = DATA_DIR / "birthdayAlbums.ts"
    ts_path.write_text(to_ts_array(all_albums), encoding="utf-8")
    print(f"Wrote {ts_path.name}")

    # Combined human-readable package
    combined = []
    combined.append("FAMILY BIRTHDAY ALBUM COLLECTION")
    combined.append("LyricsForge — 4 albums × 10 songs = 40 original tracks")
    combined.append("")
    for alb in all_albums:
        combined.append(album_to_txt(alb))
        combined.append("\n" + "=" * 72 + "\n")
    combined_path = ALBUMS_DIR / "all-birthday-albums-complete.txt"
    combined_path.write_text("\n".join(combined), encoding="utf-8")
    print(f"Wrote {combined_path.name}")

    # Quick validation
    for alb in all_albums:
        assert alb["songCount"] == 10, alb["name"]
        assert len(alb["songs"]) == 10, alb["name"]
        for s in alb["songs"]:
            assert s["lyrics"] and isinstance(s["lyrics"][0], list) and len(s["lyrics"][0]) > 8, s["id"]
            assert s["title"] and s["genre"] and s["mood"]
    print("Validation OK: 4 albums × 10 songs, lyrics present.")


