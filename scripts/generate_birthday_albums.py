def to_ts_array(album_list: list[dict[str, Any]]) -> str:
    # Compact-ish TS module; lyrics stay as string arrays for readability.
    parts = ["// Auto-generated seed data — family birthday albums (4 × 10 songs).",
             "import type { Album } from \"../types\";",
             "",
             "export const BIRTHDAY_ALBUMS: Album[] = ["]
    for alb in album_list:
        parts.append("  {")
        parts.append(f"    id: {json.dumps(alb['id'])},")
        parts.append(f"    name: {json.dumps(alb['name'])},")
        parts.append(f"    occasion: {json.dumps(alb['occasion'])},")
        parts.append(f"    comments: {json.dumps(alb['comments'])},")
        parts.append(f"    genres: {json.dumps(alb['genres'], ensure_ascii=False)},")
        parts.append(f"    songCount: {alb['songCount']},")
        parts.append(f"    language: {json.dumps(alb['language'])},")
        parts.append("    titlesReadyForReview: false,")
        parts.append("    songs: [")
        for s in alb["songs"]:
            parts.append("      {")
            for key in (
                "id", "title", "genre", "mood", "structure", "rhymeScheme",
                "customIdeas", "isApproved", "language", "musicKey",
                "titleRationale", "artistStyleName", "referenceSongTitle",
            ):
                val = s.get(key)
                if key == "isApproved":
                    parts.append(f"        isApproved: {'true' if val else 'false'},")
                elif key in ("language", "musicKey", "titleRationale", "artistStyleName", "referenceSongTitle"):
                    parts.append(f"        {key}: {json.dumps(val or '', ensure_ascii=False)},")
                else:
                    parts.append(f"        {key}: {json.dumps(val, ensure_ascii=False)},")
            parts.append("        tags: " + json.dumps(s.get("tags") or [], ensure_ascii=False) + ",")
            lyric_lines = s["lyrics"][0]
            parts.append("        lyrics: [[")
            for ln in lyric_lines:
                parts.append("          " + json.dumps(ln, ensure_ascii=False) + ",")
            parts.append("        ]],")
            parts.append("      },")
        parts.append("    ],")
        parts.append("  },")
    parts.append("];")
    parts.append("")
    parts.append("export default BIRTHDAY_ALBUMS;")
    parts.append("")
    return "\n".join(parts)


def album_to_txt(alb: dict[str, Any]) -> str:
    L = []
    L.append("=" * 72)
    L.append(f"ALBUM PACKAGE: {alb['name'].upper()}")
    L.append(f"Occasion: {alb['occasion']}")
    L.append(f"Genres: {', '.join(alb['genres'])}")
    L.append(f"Total Tracks: {alb['songCount']}")
    L.append(f"Concept: {alb['comments']}")
    L.append("=" * 72)
    L.append("")
    for i, s in enumerate(alb["songs"], 1):
        L.append("-" * 72)
        L.append(f"TRACK {i}: {s['title'].upper()}")
        L.append(f"Genre: {s['genre']} | Mood: {s['mood']} | Key: {s.get('musicKey','')}")
        L.append(f"Approved: {'YES' if s['isApproved'] else 'NO'}")
        if s.get("customIdeas"):
            L.append(f"Concept: {s['customIdeas']}")
        L.append("-" * 72)
        L.append("")
        L.append("\n".join(s["lyrics"][0]))
        L.append("")
    return "\n".join(L)


