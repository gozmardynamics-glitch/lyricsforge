def lines(*parts: str) -> list[str]:
    out: list[str] = []
    for p in parts:
        out.extend(p.strip("\n").split("\n"))
    return out


def song(
    sid: str,
    title: str,
    genre: str,
    mood: str,
    custom_ideas: str,
    lyric_lines: list[str],
    *,
    rhyme: str = "ABAB (Alternate Rhyme)",
    structure: str = "Verse - Chorus - Verse - Chorus - Bridge - Chorus - Outro",
    language: str = "English",
    key: str = "C Major",
    tags: list[str] | None = None,
    rationale: str = "",
    artist: str = "Family Studio",
    ref: str = "",
) -> dict[str, Any]:
    return {
        "id": sid,
        "title": title,
        "genre": genre,
        "mood": mood,
        "structure": structure,
        "rhymeScheme": rhyme,
        "customIdeas": custom_ideas,
        "lyrics": [lyric_lines],
        "isApproved": True,
        "language": language,
        "musicKey": key,
        "tags": tags or ["birthday", "family"],
        "titleRationale": rationale or f"Opens the emotional door for {title.lower()}.",
        "artistStyleName": artist,
        "referenceSongTitle": ref,
    }


def album(
    aid: str,
    name: str,
    occasion: str,
    comments: str,
    genres: list[str],
    songs: list[dict[str, Any]],
) -> dict[str, Any]:
    return {
        "id": aid,
        "name": name,
        "occasion": occasion,
        "comments": comments,
        "genres": genres,
        "songCount": len(songs),
        "songs": songs,
        "language": "English",
        "titlesReadyForReview": False,
        "titlesGeneratedAt": None,
    }


